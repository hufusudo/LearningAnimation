"""浏览器验收：python3 .agents/skills/webapp-testing/scripts/with_server.py
--server 'python3 -m http.server 8766 --bind 127.0.0.1' --port 8766
-- python3 偏导与可微的几何辨析/browser.test.py
"""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parent
BASE = 'http://127.0.0.1:8766/' + ROOT.name + '/'
checks = []

def check(name, condition=True):
    assert condition, name
    checks.append(name)

def range_to(page, selector, value):
    page.locator(selector).evaluate("(el,v) => {el.value=v;el.dispatchEvent(new Event('input',{bubbles:true}));el.dispatchEvent(new Event('change',{bubbles:true}));}", value)
    page.wait_for_timeout(35)

def frame(page):
    return page.evaluate("""() => ({formula:document.querySelector('#formula').textContent, curve:document.querySelector('#sceneHost').dataset.geometry, angle:document.querySelector('#thetaVal').textContent, zoom:document.querySelector('#zoomVal').textContent, verdicts:[...document.querySelectorAll('#verdicts .state')].map(n=>n.textContent),hint:document.querySelector('#hint').textContent})""")

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True,args=['--enable-unsafe-swiftshader'])
    page = browser.new_page(viewport={'width':1440,'height':1100})
    errors = []
    page.on('pageerror', lambda err: errors.append(str(err)))
    page.goto(BASE, wait_until='networkidle')
    check('真实WebGL三维渲染',page.locator('#sceneHost').get_attribute('data-renderer')=='webgl' and page.locator('#sceneHost canvas').is_visible())
    check('HTTP初始渲染', page.locator('#formula').inner_text().startswith('F1'))
    check('初始判定未揭晓', page.locator('#verdicts .state').all_text_contents() == ['待揭晓']*4)
    page.locator('[data-angle="45"]').click()
    range_to(page, '#zoom', 7)
    check('F1斜向放大仍断开', '0.500' in page.locator('#label-probe').inner_text() and '超出窗口' in page.locator('#label-probe').inner_text())
    check('缩小邻域不会自动冒充证明', page.locator('#verdicts .state').all_text_contents() == ['待揭晓']*4)
    page.locator('#reveal').click()
    check('F1判定',page.locator('#verdicts .state').all_text_contents()==['成立','不成立','不成立','不成立'])
    page.locator('[data-id="F2"]').click()
    check('F2不构造候选L',page.locator('#label-plane').is_hidden() and page.locator('#errRead').inner_text()=='—')
    check('F2两侧差商',page.locator('#secN').inner_text()=='−1.000' and page.locator('#secP').inner_text()=='+1.000')
    page.locator('[data-id="F3"]').click()
    range_to(page,'#zoom',0)
    curve_far=page.evaluate('Array.from(PDGeometry.sample("F3",45,0).mesh.positions)')
    range_to(page,'#zoom',9)
    check('F3同比放大折角保持',curve_far==page.evaluate('Array.from(PDGeometry.sample("F3",45,9).mesh.positions)'))
    check('F3误差比恒0.5',page.locator('#errRead').inner_text()=='0.500')
    page.locator('[data-id="F4"]').click()
    page.locator('#reveal').click()
    check('F4可微但偏导不连续',page.locator('#verdicts .state').all_text_contents()==['成立','成立','成立','不成立'])
    check('F4原点与附近偏导分开','P 处偏导为 0' in page.locator('#errorNote').inner_text() and page.locator('#label-slopeA').is_visible() and page.locator('#label-slopeB').is_visible())
    nearby=page.evaluate('PDGeometry.sample("F4",0,9).nearby.map(p=>p.slope)')
    check('F4两列斜率±1',abs(nearby[0]+1)<1e-6 and abs(nearby[1]-1)<1e-6)
    check('相同距离比较局部与全局误差',abs(float(page.locator('#localErr').inner_text())-float(page.locator('#errRead').inner_text()))<1e-6)
    page.locator('[data-id="F0"]').click()
    check('F0误差明确近似取样','≈' in page.locator('#errRead').inner_text() and '360' in page.locator('#errorNote').inner_text())
    page.locator('#blind').click()
    check('盲测隐藏判定',page.locator('#verdicts .state').all_text_contents()==['待揭晓']*4)
    page.locator('#blind').click()
    check('盲测揭晓',page.locator('#verdicts .state').all_text_contents()==['成立']*4)

    before_geometry=page.locator('#sceneHost').get_attribute('data-geometry')
    before_yaw=page.locator('#sceneHost').get_attribute('data-yaw')
    page.locator('#sceneHost').scroll_into_view_if_needed()
    box=page.locator('#sceneHost').bounding_box()
    page.mouse.move(box['x']+box['width']*.55,box['y']+box['height']*.32)
    page.mouse.down();page.mouse.move(box['x']+box['width']*.65,box['y']+box['height']*.38,steps=5);page.mouse.up()
    check('拖动实际旋转三维相机',page.locator('#sceneHost').get_attribute('data-yaw')!=before_yaw)
    check('旋转不改变教学参数',page.locator('#sceneHost').get_attribute('data-geometry')==before_geometry)
    for mode in ['slice','top','default']:
        page.locator('[data-camera="'+mode+'"]').click()
        check('固定视角'+mode,page.locator('[data-camera="'+mode+'"]').get_attribute('aria-pressed')=='true')
    page.locator('#showPlane').uncheck()
    check('候选平面可隐藏',page.locator('#label-plane').is_hidden())
    page.locator('#showPlane').check()
    page.locator('#showCut').uncheck()
    check('剖切标签随图层隐藏',page.locator('#label-probe').is_hidden())
    page.locator('#showCut').check()
    page.locator('#showSurface').uncheck();page.locator('#showSurface').check()
    check('图层开关不重置教学参数',page.locator('#sceneHost').get_attribute('data-geometry')==before_geometry)

    for kind in ['entry','advanced']:
        page.select_option('#tourKind',kind)
        spec=page.evaluate('(kind)=>PDModel.TOURS[kind].steps',kind)
        for i,target in enumerate(spec):
            page.locator(f'[data-step="{i}"]').click()
            check(kind+'单步'+str(i+1),page.locator('#formula').inner_text().startswith(target['sample']) and page.locator('#thetaVal').inner_text()==str(target['theta'])+'°' and page.locator('#stageTitle').inner_text()==target['title'])
        check(kind+'末步暂停',page.locator('#tourPlay').get_attribute('aria-pressed')=='false')
        page.locator('[data-step="0"]').click()
        range_to(page,'#progress',0)
        check(kind+'回退撤销未来判定',page.locator('#verdicts .state').all_text_contents()==['待揭晓']*4)
        point=float(page.locator('#progress').get_attribute('max'))*.45
        range_to(page,'#progress',point)
        before=frame(page)
        range_to(page,'#progress',point+5)
        range_to(page,'#progress',point)
        check(kind+'任意跳转可复现',frame(page)==before)

    page.locator('#tourReplay').click()
    page.select_option('#tourSpeed','2')
    page.locator('#tourPlay').click()
    page.wait_for_timeout(300)
    progress=float(page.locator('#progress').input_value())
    check('播放推进时刻',progress>0.2)
    page.locator('#tourPlay').click()
    paused=float(page.locator('#progress').input_value())
    page.wait_for_timeout(250)
    check('暂停冻结',abs(float(page.locator('#progress').input_value())-paused)<1e-6)
    page.locator('#tourPlay').click()
    page.wait_for_timeout(200)
    check('恢复续播',float(page.locator('#progress').input_value())>paused)
    page.evaluate("Object.defineProperty(document,'hidden',{configurable:true,get:()=>true});document.dispatchEvent(new Event('visibilitychange'));delete document.hidden")
    check('后台事件暂停',page.locator('#tourPlay').get_attribute('aria-pressed')=='false')
    page.locator('#motion').click()
    check('减少动效禁用自动缩放',page.locator('#auto').is_disabled())
    page.locator('#tourReplay').click()
    page.locator('#tourPlay').click()
    page.wait_for_timeout(600)
    check('减少动效逐事件播放','步骤 2' in page.locator('#stepRead').inner_text())
    page.locator('#tourPlay').click()
    stopped=page.locator('#stepRead').inner_text()
    page.wait_for_timeout(400)
    check('减少动效暂停冻结停留',page.locator('#stepRead').inner_text()==stopped)
    page.select_option('#tourSpeed','0.5')
    page.locator('#tourPlay').click()
    page.wait_for_timeout(200)
    page.select_option('#tourSpeed','2')
    page.wait_for_timeout(350)
    check('减少动效切速保留进度',page.locator('#stepRead').inner_text()!=stopped)
    page.locator('#tourPlay').click()
    page.locator('#motion').click()
    page.locator('[data-id="F1"]').click()
    page.locator('#auto').click()
    page.wait_for_timeout(120)
    page.locator('[data-angle="90"]').click()
    zoom=page.locator('#zoomVal').inner_text()
    page.wait_for_timeout(120)
    check('手动操作清理自动缩放',page.locator('#auto').get_attribute('aria-pressed')=='false' and page.locator('#zoomVal').inner_text()==zoom)
    page.locator('#reset').click()
    page.locator('h1').click()
    page.keyboard.press('ArrowRight')
    check('键盘单步','步骤 1' in page.locator('#stepRead').inner_text())
    page.keyboard.press('Home')
    check('Home归零',float(page.locator('#progress').input_value())==0)
    page.keyboard.press('Digit4')
    check('数字键选样本',page.locator('#formula').inner_text().startswith('F4'))
    page.locator('#theta').focus()
    page.keyboard.press('ArrowRight')
    check('控件不抢快捷键',page.locator('#stageTitle').inner_text()=='自由探索')
    page.locator('#reveal').click()
    page.locator('.relations summary').click()
    check('关系区域落点可见',page.locator('#dot').is_visible())
    page.locator('#fullscreen').click()
    page.wait_for_function('!!document.fullscreenElement')
    check('全屏可进入',page.evaluate('!!document.fullscreenElement'))
    page.evaluate('document.exitFullscreen()')
    page.wait_for_function('!document.fullscreenElement')
    page.screenshot(path='/tmp/pd3-final-desktop.png',full_page=True)
    for width in [1280,900,700,375]:
        page.set_viewport_size({'width':width,'height':1000})
        check(str(width)+'宽无页面溢出',not page.evaluate('document.documentElement.scrollWidth>innerWidth'))
    page.screenshot(path='/tmp/pd3-final-narrow.png',full_page=True)
    original_size=page.locator('#hint').evaluate('n=>getComputedStyle(n).fontSize')
    for _ in range(6): page.locator('#fontUp').click()
    check('字号实际放大',page.locator('#hint').evaluate('n=>getComputedStyle(n).fontSize')!=original_size)
    check('窄宽放大字号无溢出',not page.evaluate('document.documentElement.scrollWidth>innerWidth'))
    for _ in range(6): page.locator('#fontDown').click()
    page.select_option('#tourKind','advanced')
    total=float(page.locator('#progress').get_attribute('max'))
    range_to(page,'#progress',total-1)
    page.locator('#tourPlay').click()
    page.locator('#motion').click()
    check('末步切换减少动效不重播',abs(float(page.locator('#progress').input_value())-total)<1e-6 and page.locator('#tourPlay').get_attribute('aria-pressed')=='false')
    page.goto(ROOT.joinpath('index.html').as_uri(),wait_until='networkidle')
    check('file三维WebGL可用',page.locator('#sceneHost').get_attribute('data-renderer')=='webgl')
    page.locator('#tourNext').click()
    check('file单步可用',page.locator('#stepRead').inner_text()=='步骤 1 / 7')
    page.locator('#tourPlay').click()
    page.wait_for_timeout(120)
    check('file播放可用',page.locator('#tourPlay').get_attribute('aria-pressed')=='true')
    page.locator('#tourPlay').click()
    check('无脚本错误',not errors)
    page.close()

    reduced=browser.new_page(reduced_motion='reduce')
    reduced.goto(BASE,wait_until='networkidle')
    check('系统减少动效默认生效',reduced.locator('#motion').get_attribute('aria-pressed')=='true')
    reduced.close()
    fallback=browser.new_page()
    fallback.route('**/vendor/gsap.min.js',lambda route:route.abort())
    fallback.goto(BASE,wait_until='networkidle')
    check('无GSAP提示与禁用',fallback.locator('#tourPlay').is_disabled() and fallback.locator('#notice').is_visible())
    fallback.locator('[data-step="4"]').click()
    check('无GSAP单步与判定可用',fallback.locator('#formula').inner_text().startswith('F1') and fallback.locator('#verdicts .state').all_text_contents()==['成立','不成立','不成立','不成立'])
    range_to(fallback,'#progress',0)
    fallback.locator('[data-angle="90"]').click()
    check('无GSAP参数可用',fallback.locator('#thetaVal').inner_text()=='90°')
    fallback.goto(BASE+'#s=BAD&a=NaN&z=Infinity&mode=BAD&t=NaN',wait_until='networkidle')
    fallback.reload(wait_until='networkidle')
    check('非法hash回退',fallback.locator('#formula').inner_text().startswith('F1') and fallback.locator('#thetaVal').inner_text()=='20°')
    fallback.goto(BASE+'#s=F1&a=&z=',wait_until='networkidle')
    fallback.reload(wait_until='networkidle')
    check('空hash数值保留默认',fallback.locator('#thetaVal').inner_text()=='20°' and '1.2000' in fallback.locator('#zoomVal').inner_text())
    fallback.close()
    no_three=browser.new_page()
    no_three.route('**/vendor/three-r128.min.js',lambda route:route.abort())
    no_three.goto(BASE,wait_until='networkidle')
    check('Three失败显示同数据静态投影',no_three.locator('#sceneHost').get_attribute('data-renderer')=='fallback' and no_three.locator('#fallback3d path').count()>10 and no_three.locator('#graphicsNotice').is_visible())
    no_three.locator('[data-id="F3"]').click();no_three.locator('[data-angle="45"]').click()
    check('静态投影仍能切样本和方向',no_three.locator('#formula').inner_text().startswith('F3') and no_three.locator('#localErr').inner_text()=='0.500')
    no_three.close()
    no_webgl=browser.new_page()
    no_webgl.add_init_script("const get=HTMLCanvasElement.prototype.getContext;HTMLCanvasElement.prototype.getContext=function(kind,...args){return kind.includes('webgl')?null:get.call(this,kind,...args)}")
    no_webgl.goto(BASE,wait_until='networkidle')
    check('WebGL失败有静态预览',no_webgl.locator('#sceneHost').get_attribute('data-renderer')=='fallback' and no_webgl.locator('#fallback3d').is_visible())
    no_webgl.locator('[data-step="4"]').click()
    check('WebGL降级仍可浏览导览',no_webgl.locator('#stageTitle').inner_text()=='缩小邻域')
    no_webgl.close()
    browser.close()
print(json.dumps({'passed':len(checks),'checks':checks,'page_errors':errors,'screenshots':['/tmp/pd3-final-desktop.png','/tmp/pd3-final-narrow.png']},ensure_ascii=False,indent=2))
